"""Register task handlers with a decorator; the worker announces them to TaskPilot at startup.

    registry = TaskRegistry()

    class ComputeMetricsV1(Payload):
        usecase_id: str

    @registry.task("analytics.compute_usecase_metrics", queue="analytics", timeout=600)
    def compute(p: ComputeMetricsV1, ctx: HandlerContext) -> dict[str, Any]:
        ...

The payload model is the handler's first parameter type. Its JSON Schema is generated by
pydantic and registered with the API, which validates every submitted payload against it
(docs/14-DECISIONS/0009-dynamic-task-registration.md).
"""

import importlib
import inspect
import re
from collections.abc import Callable, Mapping
from dataclasses import dataclass, field
from typing import Any, TypeAlias, get_type_hints
from uuid import UUID

from pydantic import BaseModel, ConfigDict

NAME_PATTERN = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*){1,3}$")
QUEUE_PATTERN = re.compile(r"^[a-z][a-z0-9_.-]{0,62}$")
MAX_TIMEOUT_SECONDS = 86_400


class Payload(BaseModel):
    """Base for payload models: unknown fields are rejected, values are immutable."""

    model_config = ConfigDict(extra="forbid", frozen=True)


@dataclass(frozen=True, slots=True)
class HandlerContext:
    """What a handler may know about its attempt.

    job_id is stable across attempts, so use it as the idempotency key for external calls.
    deadline is a time.monotonic() value.
    """

    job_id: UUID
    attempt_no: int
    deadline: float


Handler: TypeAlias = Callable[[Any, HandlerContext], Mapping[str, Any]]


@dataclass(frozen=True, slots=True)
class TaskSpec:
    """A registered task type: what the worker runs and what it tells the API."""

    task_type: str
    version: int
    queue: str
    payload_model: type[BaseModel]
    handler: Handler
    title: str
    description: str
    example: Mapping[str, Any] | None
    timeout: int
    max_timeout: int
    max_attempts: int
    idempotent: bool
    side_effects: bool
    test_only: bool

    @property
    def key(self) -> tuple[str, int]:
        """(task_type, version)."""
        return (self.task_type, self.version)

    def definition(self) -> dict[str, Any]:
        """The registration body sent to POST /internal/v1/workers."""
        return {
            "task_type": self.task_type,
            "task_version": self.version,
            "queue": self.queue,
            "title": self.title,
            "description": self.description,
            "payload_schema": self.payload_model.model_json_schema(),
            "example": dict(self.example) if self.example is not None else None,
            "default_timeout_seconds": self.timeout,
            "max_timeout_seconds": self.max_timeout,
            "default_max_attempts": self.max_attempts,
            "idempotent": self.idempotent,
            "side_effects": self.side_effects,
            "test_only": self.test_only,
        }


def _payload_model(fn: Handler) -> type[BaseModel]:
    params = list(inspect.signature(fn).parameters)
    hints = get_type_hints(fn)
    model = hints.get(params[0]) if params else None
    if not (isinstance(model, type) and issubclass(model, BaseModel)):
        raise TypeError(
            f"{fn.__qualname__}: the first parameter must be annotated with a pydantic model"
        )
    return model


@dataclass(slots=True)
class TaskRegistry:
    """All task types one worker process can run."""

    _specs: dict[tuple[str, int], TaskSpec] = field(default_factory=dict)

    def task(
        self,
        name: str,
        *,
        version: int = 1,
        queue: str = "default",
        title: str | None = None,
        description: str | None = None,
        example: Mapping[str, Any] | None = None,
        timeout: int = 60,
        max_timeout: int | None = None,
        max_attempts: int = 3,
        idempotent: bool = True,
        side_effects: bool = False,
        test_only: bool = False,
    ) -> Callable[[Handler], Handler]:
        """Register the decorated function as task type `name` (2-4 dot-separated segments)."""

        def register(fn: Handler) -> Handler:
            limit = max_timeout or timeout
            problems = [
                msg
                for bad, msg in [
                    (
                        not NAME_PATTERN.match(name) or len(name) > 100,
                        "name must be 2-4 dot-separated lowercase segments",
                    ),
                    (version < 1, "version must be >= 1"),
                    (not QUEUE_PATTERN.match(queue), "queue must match ^[a-z][a-z0-9_.-]{0,62}$"),
                    (
                        not 1 <= timeout <= limit <= MAX_TIMEOUT_SECONDS,
                        "need 1 <= timeout <= max_timeout <= 86400",
                    ),
                    (not 1 <= max_attempts <= 10, "max_attempts must be 1-10"),
                    (
                        side_effects and not idempotent and max_attempts != 1,
                        "a non-idempotent task with side effects must use max_attempts=1",
                    ),
                    ((name, version) in self._specs, "is already registered"),
                ]
                if bad
            ]
            if problems:
                raise ValueError(f"task {name} v{version}: " + "; ".join(problems))
            model = _payload_model(fn)
            if example is not None:
                model.model_validate(example)  # a published example must be valid
            doc = inspect.getdoc(fn) or ""
            self._specs[(name, version)] = TaskSpec(
                task_type=name,
                version=version,
                queue=queue,
                payload_model=model,
                handler=fn,
                title=title or name.rsplit(".", 1)[-1].replace("_", " ").capitalize(),
                description=description or doc.split("\n\n")[0].replace("\n", " "),
                example=example,
                timeout=timeout,
                max_timeout=limit,
                max_attempts=max_attempts,
                idempotent=idempotent,
                side_effects=side_effects,
                test_only=test_only,
            )
            return fn

        return register

    def get(self, task_type: str, version: int) -> TaskSpec | None:
        """The spec for one task type version, if registered."""
        return self._specs.get((task_type, version))

    def specs(self) -> list[TaskSpec]:
        """Every registered spec, ordered by name and version."""
        return [self._specs[k] for k in sorted(self._specs)]

    def queues(self) -> list[str]:
        """Every queue a registered task routes to."""
        return sorted({s.queue for s in self._specs.values()})


def load_registry(path: str) -> TaskRegistry:
    """Import "package.module:attribute" (e.g. "livis.taskpilot_tasks:registry").

    The path comes from operator configuration (TASKPILOT_WORKER_APP), never from a job.
    """
    module_name, _, attr = path.partition(":")
    registry = getattr(importlib.import_module(module_name), attr or "registry", None)
    if not isinstance(registry, TaskRegistry):
        raise TypeError(f"{path} is not a TaskRegistry")
    return registry
